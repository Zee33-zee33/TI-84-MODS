/* Fill remaining font data with blanks */
static uint8_t font_data[FONT_CHARS * FONT_HEIGHT];
static int font_loaded = 0;

int font_init(void) {
    /* Copy embedded font to working buffer */
    memcpy(font_data, embedded_font, sizeof(embedded_font));
    
    /* Fill extended ASCII range with blanks */
    for (int i = 0x80; i < FONT_CHARS; i++) {
        for (int j = 0; j < FONT_HEIGHT; j++) {
            font_data[i * FONT_HEIGHT + j] = 0x00;
        }
    }
    
    font_loaded = 1;
    return 0;
}

int font_load_from_blob(const uint8_t *data) {
    if (!data) return -1;
    
    memcpy(font_data, data, FONT_CHARS * FONT_HEIGHT);
    font_loaded = 1;
    return 0;
}

void draw_text(int x, int y, const char *text, uint8_t color) {
    if (!font_loaded || !text) return;
    
    int cursor_x = x;
    
    for (const char *p = text; *p; p++) {
        uint8_t ch = (uint8_t)*p;
        const uint8_t *glyph = &font_data[ch * FONT_HEIGHT];
        
        /* Draw each row of the character */
        for (int row = 0; row < FONT_HEIGHT; row++) {
            uint8_t row_data = glyph[row];
            
            /* Draw each pixel in the row */
            for (int col = 0; col < FONT_WIDTH; col++) {
                if (row_data & (0x80 >> col)) {
                    draw_pixel(cursor_x + col, y + row, color);
                }
            }
        }
        
        cursor_x += FONT_WIDTH;
    }
}

void draw_number(int x, int y, int number, uint8_t color) {
    char buffer[16];
    snprintf(buffer, sizeof(buffer), "%d", number);
    draw_text(x, y, buffer, color);
}

int text_width(const char *text) {
    if (!text) return 0;
    
    int len = 0;
    for (const char *p = text; *p; p++) {
        len++;
    }
    
    return len * FONT_WIDTH;
}
